# Calibration scoring
# ---------------------------------------------------------------------------

def score_against_sample(output_df: pd.DataFrame) -> Dict:
    """
    Compare output against sample_requests.csv ground truth.
    Returns per-field match counts and a total 'exact match' count.
    Hard Rule 7: must report exact match count, not 'mostly working'.
    """
    from loaders import load_sample_requests
    sample = load_sample_requests().reset_index()

    fields = [
        "affordability_status",
        "recommended_payment_method",
    ]
    # amount_safe_to_pay and earliest_date_for_full_payment need tolerance
    numeric_fields = ["amount_safe_to_pay"]

    results = {"total": 0, "exact_match": 0, "field_matches": {}}
    for f in fields + numeric_fields + ["earliest_date_for_full_payment", "spending_changes_needed"]:
        results["field_matches"][f] = 0

    mismatches = []

    for _, gt_row in sample.iterrows():
        rid = gt_row["request_id"]
        out_row = output_df[output_df["request_id"] == rid]
        if len(out_row) == 0:
            continue

        out = out_row.iloc[0]
        results["total"] += 1
        row_exact = True

        for f in fields:
            gt_val = str(gt_row[f]).strip()
            pred_val = str(out[f]).strip()
            if gt_val == pred_val:
                results["field_matches"][f] += 1
            else:
                row_exact = False

        # Amount safe to pay — tolerance 1%
        try:
            gt_amt = float(gt_row["amount_safe_to_pay"])
            pred_amt = float(out["amount_safe_to_pay"])
            tol = max(gt_amt * 0.01, 1.0)
            if abs(gt_amt - pred_amt) <= tol:
                results["field_matches"]["amount_safe_to_pay"] += 1
            else:
                row_exact = False
        except Exception:
            row_exact = False

        # Earliest date
        gt_edate = str(gt_row.get("earliest_date_for_full_payment", "")).strip()
        pred_edate = str(out.get("earliest_date_for_full_payment", "")).strip()
        # Treat 'nan', '', 'None' as equivalent empty values
        gt_empty = gt_edate in ("nan", "", "None", "NaN")
        pred_empty = pred_edate in ("nan", "", "None", "NaN")
        if (gt_empty and pred_empty) or (gt_edate == pred_edate):
            results["field_matches"]["earliest_date_for_full_payment"] += 1
        else:
            row_exact = False

        # Spending changes
        gt_sc = str(gt_row.get("spending_changes_needed", "none")).strip()
        pred_sc = str(out.get("spending_changes_needed", "none")).strip()
        if gt_sc == pred_sc:
            results["field_matches"]["spending_changes_needed"] += 1
        else:
            row_exact = False

        if row_exact:
            results["exact_match"] += 1
        else:
            mismatches.append({
                "request_id": rid,
                "gt": gt_row.to_dict(),
                "pred": out.to_dict(),
            })

    results["mismatches"] = mismatches
    return results


def print_calibration_report(results: Dict) -> None:
    """Hard Rule 7: must print exact counts, never vague claims."""
    total = results["total"]
    exact = results["exact_match"]
    logger.info("=" * 60)
    logger.info("CALIBRATION RESULT: %d/%d exact matches", exact, total)
    logger.info("Field-level matches:")
    for field, count in results["field_matches"].items():
        logger.info("  %-40s %d/%d", field, count, total)

    if results["mismatches"]:
        logger.info("Mismatches (%d):", len(results["mismatches"]))
        for mm in results["mismatches"]:
            rid = mm["request_id"]
            gt = mm["gt"]
            pred = mm["pred"]
            logger.info("  %s:", rid)
            for f in ["affordability_status", "recommended_payment_method",
                       "amount_safe_to_pay", "earliest_date_for_full_payment",
                       "spending_changes_needed"]:
                if str(gt.get(f, "")).strip() != str(pred.get(f, "")).strip():
                    logger.info("    %s: GT=%r PRED=%r", f, gt.get(f), pred.get(f))
    logger.info("=" * 60)


