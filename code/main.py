def _load_env():
    env_path = REPO_ROOT / ".env"
    if env_path.exists():
        try:
            from dotenv import load_dotenv
            load_dotenv(env_path)
            logger.info("Loaded .env from %s", env_path)
        except Exception as e:
            logger.warning("dotenv load failed: %s", e)
    else:
        logger.info("No .env file found — using environment variables as-is")


# ---------------------------------------------------------------------------
# Token tracking (for usage_report.md)
# ---------------------------------------------------------------------------

class TokenTracker:
    def __init__(self):
        self.calls = 0
        self.input_tokens = 0
        self.output_tokens = 0
        self.model_calls: Dict[str, int] = {}

    def record(self, model: str, input_tok: int, output_tok: int):
        self.calls += 1
        self.input_tokens += input_tok
        self.output_tokens += output_tok
        self.model_calls[model] = self.model_calls.get(model, 0) + 1

    def write_report(self, num_requests: int, output_path: str):
        total_tok = self.input_tokens + self.output_tokens
        avg_per_req = total_tok / max(num_requests, 1)
        # Rough cost estimate (Groq free tier — approximately $0)
        estimated_cost = 0.0

        report = f"""# Token Usage Report

## Final Full-Dataset Run

Generated by: code/main.py
Requests processed: {num_requests}

## Model Usage

| Model | Calls |
|-------|-------|
"""
        for model, n in self.model_calls.items():
            report += f"| {model} | {n} |\n"

        report += f"""
## Token Counts

| Metric | Value |
|--------|-------|
| Total API calls | {self.calls} |
| Total input tokens | {self.input_tokens:,} |
| Total output tokens | {self.output_tokens:,} |
| Total tokens | {total_tok:,} |
| Avg tokens per request | {avg_per_req:.1f} |

## Cost Estimate

| Metric | Value |
|--------|-------|
| Provider | Groq (free tier) |
| Estimated total cost | ${estimated_cost:.4f} |
| Estimated cost per request | ${estimated_cost / max(num_requests, 1):.6f} |

*Note: Groq free tier has no per-token charge at time of run.
 Cost would be ~$0.00 for this run.*
"""
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(report)
        logger.info("Wrote usage report to %s", output_path)


# ---------------------------------------------------------------------------
# Single request processor
# ---------------------------------------------------------------------------

def run_one(
    request_id: str,
    use_sample: bool,
    use_llm: bool,
    tracker: Optional[TokenTracker] = None,
) -> Optional[dict]:
    """Process one request_id and return a dict row for output."""
    try:
        from retrieval import get_request_context
        from extract_context import build_amendments
        from pipeline import process_request

        # Phase 8: Extract amendments from messages + images
        ctx = get_request_context(request_id, use_sample=use_sample)
        amendments = {}
        if use_llm:
            amendments = build_amendments(
                user_id=ctx["request"]["user_id"],
                request_id=request_id,
                request_date=pd.Timestamp(ctx["request"]["request_date"]),
                events=ctx["events"],
                messages=ctx["messages"],
                images=ctx["images"],
                home_currency=ctx["home_currency"],
                use_llm=True,
            )
        elif use_sample:
            # Use hardcoded fixtures for --no-llm calibration
            from fixtures import get_sample_amendments
            amendments = get_sample_amendments(request_id)

        # Full pipeline
        rec = process_request(
            request_id=request_id,
            use_sample=use_sample,
            use_llm=use_llm,
            amendments=amendments,
        )

        return {
            "request_id": rec.request_id,
            "amount_safe_to_pay": round(rec.amount_safe_to_pay, 2),
            "affordability_status": rec.affordability_status,
            "recommended_payment_method": rec.recommended_payment_method,
            "payment_plan": rec.payment_plan,
            "earliest_date_for_full_payment": rec.earliest_date_for_full_payment,
            "spending_changes_needed": rec.spending_changes_needed,
            "decision_explanation": rec.decision_explanation,
        }

    except Exception as e:
        logger.error("FAILED: %s — %s", request_id, e)
        logger.debug(traceback.format_exc())
        return None


