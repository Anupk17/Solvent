# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Buy or Wait? financial agent")
    parser.add_argument("--sample", action="store_true", help="Run against sample_requests.csv")
    parser.add_argument("--no-llm", action="store_true", help="Skip all LLM calls (deterministic only)")
    parser.add_argument("--request", type=str, help="Process a single request_id")
    parser.add_argument("--no-calibration", action="store_true", help="Skip calibration scoring (sample run)")
    args = parser.parse_args()

    _load_env()

    use_llm = not args.no_llm
    use_sample = args.sample
    single_request = args.request

    if use_llm and not os.environ.get("GROQ_API_KEY"):
        logger.warning("GROQ_API_KEY not set — running without LLM (use --no-llm to suppress this warning)")
        use_llm = False

    # Load request IDs
    from loaders import load_requests, load_sample_requests
    if use_sample:
        req_df = load_sample_requests()
        output_path = SAMPLE_OUTPUT_PATH
        logger.info("SAMPLE RUN: %d requests", len(req_df))
    else:
        req_df = load_requests()
        output_path = OUTPUT_PATH
        logger.info("FULL RUN: %d requests", len(req_df))

    if single_request:
        request_ids = [single_request]
    else:
        request_ids = list(req_df.index)

    tracker = TokenTracker()
    rows = []
    start_time = time.time()

    for i, rid in enumerate(request_ids):
        t0 = time.time()
        logger.info("[%d/%d] Processing %s", i + 1, len(request_ids), rid)
        row = run_one(rid, use_sample=use_sample, use_llm=use_llm, tracker=tracker)
        if row is None:
            # Fallback row — keeps pipeline running
            requested = float(req_df.loc[rid]["requested_amount"]) if rid in req_df.index else 0.0
            row = {
                "request_id": rid,
                "amount_safe_to_pay": 0.0,
                "affordability_status": "not_affordable",
                "recommended_payment_method": "not_recommended",
                "payment_plan": "none",
                "earliest_date_for_full_payment": "",
                "spending_changes_needed": "none",
                "decision_explanation": "Processing error — could not compute recommendation.",
            }
        rows.append(row)
        elapsed = time.time() - t0
        logger.info("  -> %s | %s | safe=%.2f | %s | %.1fs",
                    rid,
                    row["affordability_status"],
                    row["amount_safe_to_pay"],
                    row["recommended_payment_method"],
                    elapsed)

    # Build output DataFrame
    output_df = pd.DataFrame(rows)

    # Write output
    from validator import write_output
    write_output(output_df, output_path, req_df)

    total_time = time.time() - start_time
    logger.info(
        "Total time: %.1fs | %.2fs per request | %d requests",
        total_time, total_time / max(len(request_ids), 1), len(request_ids)
    )

    # Calibration scoring
    if use_sample and not args.no_calibration:
        results = score_against_sample(output_df)
        print_calibration_report(results)

    # Usage report (for full runs)
    if not use_sample:
        usage_report_path = str(CODE_DIR / "evaluation" / "usage_report.md")
        tracker.write_report(len(request_ids), usage_report_path)

    logger.info("Done. Output written to %s", output_path)


if __name__ == "__main__":
    main()
